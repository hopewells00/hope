"""
راهنمای راه‌اندازی ربات بله (Bale Messenger)

چون بله از پروتکل MTProto استفاده نمی‌کند، نیازی به SESSION_STRING نیست.
فقط به توکن ربات بله احتیاج داری.

─────────────────────────────────────────────────
 مرحله ۱: ساخت ربات در بله
─────────────────────────────────────────────────
1. به پیام‌رسان بله وارد شو
2. با @BotFather چت کن
3. دستور /newbot را بزن
4. نام و نام کاربری ربات را وارد کن
5. توکن دریافتی را کپی کن (مثال: 12345678:ABCDEFGabcdefg...)

─────────────────────────────────────────────────
 مرحله ۲: تنظیم Environment Variables
─────────────────────────────────────────────────
متغیرهای زیر را در Railway / VPS / سرور خود تنظیم کن:

  BOT_TOKEN       = توکن ربات بله (از BotFather)
  ADMIN_ID        = شناسه عددی ادمین (User ID)
  ZIP_PASS        = رمز عبور برای فایل ZIP
  CRYPT_PASS      = رمز عبور برای رمزگذاری لینک
  SMS_API_KEY     = کلید API سرویس sms.ir
  SMS_LINE_NUMBER = خط ارسال پیامک
  TARGET_PHONE    = شماره دریافت‌کننده پیامک

متغیرهای اختیاری:
  MESSAGE_COUNT   = تعداد پیام‌های export (پیش‌فرض: 30)
  MAX_ZIP_MB      = حداکثر حجم ZIP به مگابایت (پیش‌فرض: 50)
  IMGURL_SESSION  = کوکی سشن imgurl.ir (اگه اکانت داری)

─────────────────────────────────────────────────
 مرحله ۳: پیدا کردن ADMIN_ID
─────────────────────────────────────────────────
1. ربات @userinfobot را در بله جستجو کن
2. یک پیام به آن بفرست
3. شناسه عددی خودت (id) را دریافت خواهی کرد

─────────────────────────────────────────────────
 مرحله ۴: اجرای ربات
─────────────────────────────────────────────────
  pip install -r requirements.txt
  python main.py

─────────────────────────────────────────────────
 مرحله ۵: افزودن کانال‌ها
─────────────────────────────────────────────────
روش اول (خودکار):
  ربات را به کانال مورد نظر اضافه کن و ادمین کن
  ربات خودکار کانال را ثبت می‌کند

روش دوم (دستی):
  در چت با ربات بنویس:
  /addchannel @channel_username
  یا:
  /addchannel -1001234567890

─────────────────────────────────────────────────
 استفاده از ربات
─────────────────────────────────────────────────
  /start    - نمایش راهنما
  /channels - مشاهده و انتخاب کانال برای export
  /addchannel - افزودن کانال جدید

نکته: ربات باید ادمین کانال باشد تا بتواند پیام‌ها را دریافت کند.
"""

